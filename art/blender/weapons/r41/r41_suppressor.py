"""R41 S-3 '말벌집' 진압 산탄총 (노획품).

R41 진압반(타이다 휘하)의 돌입·근거리 제압용 6연발 회전 약실 산탄총. 펌프를 당기면 육각 약실이 60°씩 돈다.
약실 옆 육각 창으로 앰버색 산탄 탄피가 보인다(벌집). 총구 머리의 톱니는 문짝을 부수는 돌파용.
방패와 함께 쓰도록 개머리 대신 짧은 어깨 받침만 있다. 도장은 K-7과 같은 PV 기준(회백 + 앰버 + 어두운 손잡이).
전장 0.44 m.

npm run model -- art/blender/weapons/r41/r41_suppressor.py
npm run shot -- weapons/r41/r41_suppressor.glb --views side,34,top,muzzle --focus r41_suppressor
"""
import math
import os
import sys

sys.path.insert(0, os.path.join(os.environ["COMBATIUM_ROOT"], "art", "blender", "lib"))
import cb  # noqa: E402
import r41  # noqa: E402

cb.reset()
M = r41.mats()
BORE_Z = 0.086
DRUM_C = (0, 0.056, 0.064)
DRUM_R = 0.034
HEAD_C = (0, 0.252, 0.073)

OCT = [(-0.020, 0.026), (0.020, 0.026), (0.0225, 0.035), (0.0225, 0.098), (0.012, 0.115),
       (-0.012, 0.115), (-0.0225, 0.098), (-0.0225, 0.035)]

# ---------------------------------------------------------------- 1차: 뒤 몸통 · 앞 요크 · 상하 스트랩
r41.faceted("receiver", [(-0.070, 0.028), (0.020, 0.028), (0.020, 0.112), (-0.042, 0.113), (-0.070, 0.100)],
            OCT, ch=0.0015, mat=M["light"])
r41.chbox("top_strap", (0.020, 0.080, 0.012), (0, 0.056, 0.1015), ch=0.002, mat=M["light"])
r41.chbox("bottom_strap", (0.016, 0.080, 0.010), (0, 0.056, 0.026), ch=0.002, mat=M["shell"])
for sx in (1, -1):
    r41.chbox(f"rcv_stripe{sx}", (0.0014, 0.086, 0.0034), (sx * 0.0229, -0.026, 0.0380), mat=M["amber"])
r41.faceted("yoke", [(0.091, 0.022), (0.117, 0.022), (0.117, 0.104), (0.091, 0.108)],
            [(-0.017, 0.020), (0.017, 0.020), (0.022, 0.030), (0.022, 0.094), (0.010, 0.110),
             (-0.010, 0.110), (-0.022, 0.094), (-0.022, 0.030)], ch=0.0015, mat=M["light"])
r41.cyl_y("drum_axle", 0.0050, 0.008, (0, 0.1205, DRUM_C[2]), verts=12, mat=M["steel"])

# 어깨 받침 (짧은 스텁)
r41.chbox("brace_strut", (0.011, 0.064, 0.013), (0, -0.098, 0.084), ch=0.002, mat=M["metal"])
r41.chbox("brace_strut2", (0.008, 0.056, 0.008), (0, -0.098, 0.060), rot=(-24, 0, 0), ch=0.0015, mat=M["metal"])
r41.faceted("brace_pad", [(-0.146, 0.044), (-0.128, 0.044), (-0.124, 0.110), (-0.136, 0.114), (-0.148, 0.104)],
            [(-0.015, 0.026), (0.015, 0.026), (0.020, 0.040), (0.020, 0.104), (0.012, 0.120),
             (-0.012, 0.120), (-0.020, 0.104), (-0.020, 0.040)], ch=0.002, mat=M["shell"])
r41.chbox("brace_face", (0.032, 0.004, 0.058), (0, -0.1485, 0.076), rot=(7, 0, 0), ch=0.0015, mat=M["metal"])

# ---------------------------------------------------------------- 손잡이 · 방아쇠
grip_pts = [(-0.028, -0.050), (0.014, -0.050), (0.015, -0.040), (0.0150, -0.033), (0.0200, -0.026),
            (0.0185, -0.017), (0.0230, -0.008), (0.0215, 0.001), (0.0265, 0.010), (0.027, 0.032),
            (-0.010, 0.032), (-0.017, 0.010), (-0.024, -0.020), (-0.027, -0.040)]
r41.prof("grip", grip_pts, 0.027, ch=0.004, seg=2, mat=M["shell"])
r41.prof("grip_strap", [(-0.0285, -0.044), (-0.0245, -0.044), (-0.012, 0.030), (-0.016, 0.030)], 0.021,
         ch=0.001, mat=M["shell"])
r41.chbox("grip_base", (0.029, 0.044, 0.006), (0, -0.007, -0.050), ch=0.002, mat=M["metal"])
r41.prof("guard", [(0.016, -0.016), (0.080, -0.016), (0.091, -0.005), (0.091, 0.030), (0.0835, 0.030),
                   (0.0835, -0.002), (0.0775, -0.0085), (0.016, -0.0085)], 0.012, ch=0.0015, mat=M["light"])
TRIG_PIVOT = (0, 0.050, 0.030)
trigger = r41.prof("trigger_blade", [(-0.003, 0.0), (0.004, 0.0), (0.0035, -0.010), (0.0060, -0.019),
                                     (0.0025, -0.026), (-0.0030, -0.025), (-0.0015, -0.012)],
                   0.006, loc=TRIG_PIVOT, ch=0.0008, mat=M["metal"])

# ---------------------------------------------------------------- 총열 · 펌프 가이드
r41.tube("barrel", 0.0150, 0.0108, 0.122, (0, 0.177, BORE_Z), verts=24, mat=M["metal"], ch=0.001)
r41.cyl_y("guide", 0.0050, 0.124, (0, 0.177, 0.056), verts=12, mat=M["steel"])
# 열 차폐 (위, 회백) + 통풍 구멍 + 앰버 줄
r41.faceted("shroud", [(0.118, 0.090), (0.228, 0.090), (0.228, 0.106), (0.124, 0.108)],
            [(-0.017, 0.088), (0.017, 0.088), (0.017, 0.100), (0.008, 0.108), (-0.008, 0.108), (-0.017, 0.100)],
            ch=0.001, mat=M["light"])
for sx in (1, -1):
    r41.slits(f"shroud_vent{sx}", (sx * 0.0173, 0.140, 0.097), (0, 0.022, 0), 4, (0.0012, 0.013, 0.0042), M["shell"])
    r41.chbox(f"shroud_stripe{sx}", (0.0012, 0.104, 0.0022), (sx * 0.0173, 0.174, 0.0910), mat=M["amber"])

# ---------------------------------------------------------------- 총구 머리 (육각 + 전극 4가닥)
r41.ngon_prism("head", 6, 0.034, 0.032, HEAD_C, mat=M["shell"], ch=0.0018)
r41.ngon_prism("head_band", 6, 0.0345, 0.005, (0, 0.2385, HEAD_C[2]), mat=M["amber"], ch=0.0006)
r41.tube("muzzle_lip", 0.0140, 0.0100, 0.006, (0, 0.2685, BORE_Z), verts=16, mat=M["steel"])
r41.cyl_y("bore", 0.0100, 0.002, (0, 0.2660, BORE_Z), verts=16, mat=M["shell"])
r41.cyl_y("guide_cap", 0.0060, 0.004, (0, 0.2685, 0.056), verts=12, mat=M["metal"])
# 돌파용 톱니 (총구 머리 앞 모서리 네 곳)
for sx in (1, -1):
    for sz in (1, -1):
        p = (sx * 0.0200, 0.2725, HEAD_C[2] + sz * 0.0150)
        t = r41.cyl_y(f"tooth{sx}{sz}", 0.0062, 0.014, p, r_front=0.0010, verts=4, mat=M["steel"])
        t.rotation_euler.y = 0.785
# 앞 가늠쇠
r41.chbox("front_riser", (0.007, 0.014, 0.020), (0, 0.250, 0.1115), ch=0.0012, mat=M["shell"])
r41.chbox("front_blade", (0.0028, 0.006, 0.008), (0, 0.252, 0.1245), ch=0.0005, mat=M["metal"])
r41.chbox("front_dot", (0.0018, 0.0010, 0.0018), (0, 0.2488, 0.1265), mat=M["glow_amber"])

# ---------------------------------------------------------------- 뒤 가늠자 (고리) · 충전 등줄
r41.chbox("rear_post", (0.008, 0.010, 0.010), (0, -0.040, 0.1170), ch=0.0012, mat=M["shell"])
r41.tube("rear_ring", 0.0075, 0.0045, 0.004, (0, -0.040, 0.1265), verts=16, mat=M["metal"])
r41.chbox("spine", (0.014, 0.044, 0.005), (0, 0.000, 0.1145), ch=0.0012, mat=M["shell"])
for i in range(4):
    r41.chbox(f"spine_rib{i}", (0.0150, 0.0040, 0.0025), (0, -0.015 + i * 0.010, 0.1175), mat=M["shell"])

# ---------------------------------------------------------------- 표식 · 측면 디테일
r41.elf_logo("L_", (-0.0229, -0.032, 0.072), 0.034, axis="X", sign=-1, mat=M["shell"])
r41.elf_logo("brace_", (0.0, -0.1505, 0.077), 0.030, axis="Y", sign=-1, mat=M["amber"])
r41.stencil_bars("R_", (0.0229, -0.040, 0.092), axis="X", sign=1, h=0.007, mat=M["shell"], pattern=(1, 0, 1, 1, 1, 0, 1))
# 오른쪽 장전 게이트
r41.chbox("load_gate", (0.0022, 0.024, 0.030), (0.0232, 0.002, 0.064), ch=0.0008, mat=M["metal"])
r41.cyl_z("gate_hinge", 0.0022, 0.032, (0.0240, -0.011, 0.064), verts=8, mat=M["steel"])
for sx in (1, -1):
    for y, z in ((-0.058, 0.040), (0.008, 0.040), (-0.058, 0.098)):
        r41.screw(f"rcv_screw{sx}{y}{z}", (sx * 0.0230, y, z), "X", mat=M["metal"])
    r41.screw(f"yoke_screw{sx}", (sx * 0.0225, 0.104, 0.040), "X", mat=M["steel"])
# 멜빵 고리 + 노획 태그
r41.tube("sling_loop", 0.0060, 0.0040, 0.0025, (-0.0232, 0.104, 0.030), axis="X", verts=12, mat=M["steel"])
r41.capture_tag("cap_", (-0.0244, 0.104, 0.024), mat_tag=M["ceramic"], mat_cord=M["amber"])

# ---------------------------------------------------------------- 펌프 (움직이는 파츠)
pump = [r41.faceted("pump_body", [(0.124, 0.040), (0.198, 0.040), (0.204, 0.050), (0.204, 0.071), (0.124, 0.071),
                                  (0.120, 0.060)],
                    [(-0.013, 0.038), (0.013, 0.038), (0.019, 0.046), (0.019, 0.066), (0.012, 0.073),
                     (-0.012, 0.073), (-0.019, 0.066), (-0.019, 0.046)], ch=0.002, mat=M["shell"])]
for i in range(5):
    pump.append(r41.chbox(f"pump_rib{i}", (0.0395, 0.0030, 0.020), (0, 0.140 + i * 0.012, 0.056), ch=0.0008, mat=M["metal"]))

# ---------------------------------------------------------------- 회전 약실 (움직이는 파츠, Y축 회전)
drum = [r41.ngon_prism("drum_body", 6, DRUM_R, 0.068, DRUM_C, mat=M["shell"], ch=0.0025)]
drum.append(r41.ngon_prism("drum_ring_F", 6, DRUM_R * 0.97, 0.006, (0, DRUM_C[1] + 0.030, DRUM_C[2]), mat=M["metal"], ch=0.0008))
drum.append(r41.ngon_prism("drum_ring_B", 6, DRUM_R * 0.97, 0.006, (0, DRUM_C[1] - 0.030, DRUM_C[2]), mat=M["metal"], ch=0.0008))
apo = DRUM_R * math.cos(math.radians(30))
for k in range(6):
    a = math.radians(30 + 60 * k)
    n = (math.cos(a), 0.0, -math.sin(a))
    phi = math.degrees(math.atan2(n[0], n[2]))
    for j, dy in enumerate((-0.0135, 0.0135)):
        c = (DRUM_C[0] + n[0] * (apo + 0.0008), DRUM_C[1] + dy, DRUM_C[2] + n[2] * (apo + 0.0008))
        o = cb.cylinder(f"cell{k}{j}", radius=0.0100, depth=0.0024, loc=c, rot=(0, phi, 0), verts=6, material=M["metal"])
        drum.append(o)
        c2 = (c[0] + n[0] * 0.0010, c[1], c[2] + n[2] * 0.0010)
        # 창 너머로 보이는 산탄 탄피 (앰버)
        drum.append(cb.cylinder(f"shell_hull{k}{j}", radius=0.0070, depth=0.0010, loc=c2, rot=(0, phi, 0), verts=6,
                                material=M["amber"]))

r41.finish(
    "r41_suppressor", "weapons/r41/r41_suppressor.glb",
    moving={
        "cylinder": (drum, DRUM_C),
        "pump": (pump, (0, 0.162, 0.056)),
        "trigger": ([trigger], TRIG_PIVOT),
    },
    anchors={
        "muzzle": (0, 0.270, BORE_Z),
        "grip_support": (0, 0.162, 0.040),
        "sight_eye": (0, -0.120, 0.1265),
        "eject": (0.026, 0.002, 0.064),
        "mag_well": (0.026, 0.002, 0.064),
    },
    props={"outline": 0.002, "fpOffset": "0.16,-0.17,-0.38", "fpRot": "0,5,0"},
)
