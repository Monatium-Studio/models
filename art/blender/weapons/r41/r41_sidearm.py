    for y, z in ((-0.024, 0.034), (0.030, 0.030), (0.060, 0.040)):
        r41.cyl_x(f"pin{sx}{y}", 0.0018, 0.0012, (sx * 0.0113, y, z), verts=8, mat=M["steel"])
